# =========================
# START
# =========================

async def start(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    user_id = update.effective_user.id

    user_modes[user_id] = None

    await update.message.reply_text(
        "🧠 ПСИХОРАЗБОР\n\n"
        "Разберём переписку, отношения "
        "или сложную ситуацию.\n\n"
        "Выбирай 👇",
        reply_markup=ReplyKeyboardMarkup(
            keyboard,
            resize_keyboard=True
        )
    )


# =========================
# ОБРАБОТКА СООБЩЕНИЙ
# =========================

async def handle_message(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    user_id = update.effective_user.id
    text = update.message.text

    # -------------------------
    # КНОПКА ПЕРЕПИСКИ
    # -------------------------

    if text == "💬 Разбор переписки":

        user_modes[user_id] = "chat"

        await update.message.reply_text(
            "💬 Пришли переписку целиком.\n\n"
            "Можно просто скопировать сообщения "
            "и отправить их сюда.\n\n"
            "Чем больше контекста — тем точнее разбор."
        )

        return

    # -------------------------
    # КНОПКА СИТУАЦИИ
    # -------------------------

    if text == "🧠 Разбор ситуации":

        user_modes[user_id] = "situation"

        await update.message.reply_text(
            "🧠 Опиши ситуацию своими словами.\n\n"
            "Например:\n\n"
            "«Девушка раньше постоянно писала первой, "
            "а последние несколько дней отвечает коротко. "
            "Что это может значить?»"
        )

        return

    # -------------------------
    # ОТНОШЕНИЯ
    # -------------------------

    if text == "❤️ Отношения":

        user_modes[user_id] = "relationship"

        await update.message.reply_text(
            "❤️ Расскажи, что происходит в отношениях.\n\n"
            "Опиши ситуацию максимально подробно."
        )

        return

    # -------------------------
    # ТРЕВОГА
    # -------------------------

    if text == "😰 Тревога и стресс":

        user_modes[user_id] = "stress"

        await update.message.reply_text(
            "😰 Расскажи, что тебя беспокоит.\n\n"
            "Я помогу разобрать ситуацию "
            "и предложу практические шаги."
        )

        return

    # -------------------------
    # ТЕСТ
    # -------------------------

    if text == "🧪 Психологический тест":

        await update.message.reply_text(
            "🧪 Раздел тестов пока готовится.\n\n"
            "Скоро здесь появятся тесты "
            "с персональным разбором."
        )

        return

    # -------------------------
    # ПРОВЕРЯЕМ РЕЖИМ
    # -------------------------

    mode = user_modes.get(user_id)

    if not mode:

        await update.message.reply_text(
            "Выбери нужный раздел в меню 👇"
        )

        return

    # -------------------------
    # СООБЩЕНИЕ АНАЛИЗА
    # -------------------------

    await update.message.reply_text(
        "🧠 Анализирую..."
    )

    # -------------------------
    # ВЫБИРАЕМ ПРОМПТ
    # -------------------------

    if mode == "chat":

        task_prompt = CHAT_PROMPT

    elif mode == "situation":

        task_prompt = SITUATION_PROMPT

    elif mode == "relationship":

        task_prompt = RELATIONSHIP_PROMPT

    elif mode == "stress":

        task_prompt = STRESS_PROMPT

    else:

        task_prompt = SITUATION_PROMPT

    # -------------------------
    # СОЗДАЁМ ЗАПРОС
    # -------------------------

    final_prompt = (
        SYSTEM_PROMPT
        + "\n\n"
        + task_prompt
        + "\n\n"
        + "СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЯ:\n"
        + text
    )

    # -------------------------
    # GEMINI
    # -------------------------

    try:

        response = client.models.generate_content(
            model=MODEL,
            contents=final_prompt
        )

        answer = response.text

        if not answer:

            raise RuntimeError(
                "Gemini вернул пустой ответ"
            )

        # Telegram имеет ограничение на длину сообщения.
        # Поэтому длинный ответ разбиваем на части.

        max_length = 4000

        for i in range(0, len(answer), max_length):

            await update.message.reply_text(
                answer[i:i + max_length]
            )

    except Exception as e:

        logging.exception(
            "Ошибка Gemini"
        )

        await update.message.reply_text(
            "❌ Ошибка при обращении к Gemini.\n\n"
            "Техническая информация:\n"
            + str(e)[:2500]
        )


# =========================
# ЗАПУСК
# =========================

def main():

    print("Запускаю ПСИХОРАЗБОР...")

    app = Application.builder().token(
        TELEGRAM_TOKEN
    ).build()

    app.add_handler(
        CommandHandler(
            "start",
            start
        )
    )

    app.add_handler(
        MessageHandler(
            filters.TEXT & ~filters.COMMAND,
            handle_message
        )
    )

    print(
        "ПСИХОРАЗБОР успешно запущен."
    )

    app.run_polling()


# =========================
# MAIN
# =========================

if __name__ == "__main__":
    main()
