# ============================================================
# START
# ============================================================

async def start(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    user_id = update.effective_user.id

    user_modes[user_id] = None

    await update.message.reply_text(
        "🧠 ПСИХОРАЗБОР\n\n"
        "Разберём переписку, скриншот, "
        "отношения или ситуацию.\n\n"
        "Выбирай 👇",

        reply_markup=ReplyKeyboardMarkup(
            keyboard,
            resize_keyboard=True
        )
    )


# ============================================================
# АНАЛИЗ СКРИНШОТА
# ============================================================

async def handle_photo(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    user_id = update.effective_user.id

    logging.info(
        "Получен скриншот от пользователя %s",
        user_id
    )

    await update.message.reply_text(
        "📸 Получил скриншот.\n\n"
        "🧠 Читаю переписку и анализирую..."
    )

    try:

        # Получаем самое качественное фото,
        # которое прислал Telegram
        photo = update.message.photo[-1]

        # Получаем файл Telegram
        telegram_file = await context.bot.get_file(
            photo.file_id
        )

        # Скачиваем изображение в память
        image_bytes = await telegram_file.download_as_bytearray()

        # Переводим изображение в Base64
        image_b64 = base64.b64encode(
            bytes(image_bytes)
        ).decode("utf-8")

        # Формируем инструкцию
        prompt = (
            SYSTEM_PROMPT
            + "\n\n"
            + SCREENSHOT_PROMPT
        )

        # ====================================================
        # GEMINI INTERACTIONS API
        # ====================================================

        response = client.interactions.create(
            model=MODEL,

            input=[
                {
                    "type": "text",
                    "text": prompt
                },
                {
                    "type": "image",
                    "data": image_b64,
                    "mime_type": "image/jpeg"
                }
            ]
        )

        # Получаем текст ответа
        answer = response.output_text

        if not answer:

            raise RuntimeError(
                "Gemini вернул пустой ответ"
            )

        # Telegram ограничивает длину сообщения,
        # поэтому длинный ответ разбиваем
        for i in range(
            0,
            len(answer),
            4000
        ):

            await update.message.reply_text(
                answer[i:i + 4000]
            )

    except Exception as e:

        logging.exception(
            "Ошибка анализа скриншота"
        )

        await update.message.reply_text(
            "❌ Ошибка при анализе скриншота:\n\n"
            + str(e)[:3000]
        )


# ============================================================
# ОБРАБОТКА ТЕКСТА
# ============================================================

async def handle_message(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    user_id = update.effective_user.id

    text = update.message.text


    # ========================================================
    # РАЗБОР ПЕРЕПИСКИ
    # ========================================================

    if text == "💬 Разбор переписки":

        user_modes[user_id] = "chat"

        await update.message.reply_text(
            "💬 Пришли переписку целиком.\n\n"
            "Можно просто скопировать сообщения "
            "и отправить их сюда."
        )

        return


    # ========================================================
    # АНАЛИЗ СКРИНШОТА
    # ========================================================

    if text == "📸 Анализ скриншота":

        user_modes[user_id] = "screenshot"

        await update.message.reply_text(
            "📸 Пришли скриншот переписки.\n\n"
            "Я прочитаю сообщения и попробую определить:\n\n"
            "📊 интерес\n"
            "💬 инициативу\n"
            "🟢 признаки интереса\n"
            "🔴 тревожные моменты\n"
            "🎯 что делать\n"
            "✍️ что написать"
        )

        return


    # ========================================================
    # РАЗБОР СИТУАЦИИ
    # ========================================================

    if text == "🧠 Разбор ситуации":

        user_modes[user_id] = "situation"

        await update.message.reply_text(
            "🧠 Опиши ситуацию своими словами."
        )

        return


    # ========================================================
    # ОТНОШЕНИЯ
    # ========================================================

    if text == "❤️ Отношения":

        user_modes[user_id] = "relationship"

        await update.message.reply_text(
            "❤️ Расскажи, что происходит "
            "в отношениях."
        )

        return


    # ========================================================
    # ТРЕВОГА
    # ========================================================

    if text == "😰 Тревога и стресс":

        user_modes[user_id] = "stress"

        await update.message.reply_text(
            "😰 Расскажи, что тебя сейчас беспокоит."
        )

        return


    # ========================================================
    # ТЕСТЫ
    # ========================================================

    if text == "🧪 Психологический тест":

        await update.message.reply_text(
            "🧪 Раздел тестов пока готовится.\n\n"
            "Следующим обновлением добавим "
            "полноценные тесты с результатами."
        )

        return


    # ========================================================
    # ПРОВЕРЯЕМ РЕЖИМ
    # ========================================================

    mode = user_modes.get(user_id)

    if not mode:

        await update.message.reply_text(
            "Выбери раздел в меню 👇"
        )

        return


    # ========================================================
    # ЕСЛИ ПОЛЬЗОВАТЕЛЬ В РЕЖИМЕ СКРИНШОТА
    # ========================================================

    if mode == "screenshot":

        await update.message.reply_text(
            "📸 Для этого режима отправь именно "
            "скриншот или фотографию переписки."
        )

        return


    # ========================================================
    # СООБЩЕНИЕ
    # ========================================================

    await update.message.reply_text(
        "🧠 Анализирую..."
    )


    # ========================================================
    # ВЫБИРАЕМ ПРОМПТ
    # ========================================================

    if mode == "chat":

        task = CHAT_PROMPT

    elif mode == "situation":

        task = SITUATION_PROMPT

    elif mode == "relationship":

        task = RELATIONSHIP_PROMPT

    else:

        task = STRESS_PROMPT


    # ========================================================
    # ФИНАЛЬНЫЙ PROMPT
    # ========================================================

    prompt = (
        SYSTEM_PROMPT
        + "\n\n"
        + task
        + "\n\n"
        + "СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЯ:\n"
        + text
    )


    # ========================================================
    # GEMINI
    # ========================================================

    try:

        response = client.interactions.create(
            model=MODEL,
            input=prompt
        )

        answer = response.output_text

        if not answer:

            raise RuntimeError(
                "Gemini вернул пустой ответ"
            )

        # Разбиваем длинные ответы
        for i in range(
            0,
            len(answer),
            4000
        ):

            await update.message.reply_text(
                answer[i:i + 4000]
            )

    except Exception as e:

        logging.exception(
            "Ошибка Gemini"
        )

        await update.message.reply_text(
            "❌ Ошибка Gemini:\n\n"
            + str(e)[:3000]
        )


# ============================================================
# ЗАПУСК
# ============================================================

def main():

    print(
        "🧠 ПСИХОРАЗБОР запускается..."
    )

    app = Application.builder().token(
        TELEGRAM_TOKEN
    ).build()


    # Команда /start
    app.add_handler(
        CommandHandler(
            "start",
            start
        )
    )


    # Фотографии
    app.add_handler(
        MessageHandler(
            filters.PHOTO,
            handle_photo
        )
    )


    # Обычный текст
    app.add_handler(
        MessageHandler(
            filters.TEXT & ~filters.COMMAND,
            handle_message
        )
    )


    print(
        "🟢 ПСИХОРАЗБОР успешно запущен."
    )

    app.run_polling()


# ============================================================
# ЗАПУСК ПРОГРАММЫ
# ============================================================

if __name__ == "__main__":

    main()
